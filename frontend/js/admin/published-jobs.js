/* ==================================================
   SEARCH + FILTER
================================================== */

function applyFilters() {

    const searchTerm =
        jobSearch
            ? jobSearch.value
                .trim()
                .toLowerCase()
            : "";


    const selectedStatus =
        statusFilter
            ? statusFilter.value
            : "all";


    const selectedCategory =
        categoryFilter
            ? categoryFilter.value
            : "all";


    filteredJobs =
        publishedJobs.filter(job => {


            const matchesSearch =
                !searchTerm ||

                job.title
                    .toLowerCase()
                    .includes(searchTerm) ||

                job.company
                    .toLowerCase()
                    .includes(searchTerm) ||

                job.category
                    .toLowerCase()
                    .includes(searchTerm) ||

                job.location
                    .toLowerCase()
                    .includes(searchTerm);


            const matchesStatus =
                selectedStatus === "all" ||
                job.status === selectedStatus;


            const matchesCategory =
                selectedCategory === "all" ||
                job.categoryId === selectedCategory;


            return (
                matchesSearch &&
                matchesStatus &&
                matchesCategory
            );

        });


    sortFilteredJobs();


    currentPageNumber = 1;


    renderAll();

}



/* ==================================================
   SORT
================================================== */

function sortFilteredJobs() {

    const sortValue =
        sortJobs
            ? sortJobs.value
            : "newest";


    filteredJobs.sort((a, b) => {

        if (sortValue === "newest") {

            return new Date(b.publishedAt)
                - new Date(a.publishedAt);

        }


        if (sortValue === "oldest") {

            return new Date(a.publishedAt)
                - new Date(b.publishedAt);

        }


        if (sortValue === "company") {

            return a.company.localeCompare(
                b.company
            );

        }


        if (sortValue === "expiry") {

            return new Date(a.expiresAt)
                - new Date(b.expiresAt);

        }


        return 0;

    });

}



/* ==================================================
   STATISTICS
================================================== */

function updateStatistics() {

    const total =
        publishedJobs.length;


    const active =
        publishedJobs.filter(
            job => job.status === "published"
        ).length;


    const closed =
        publishedJobs.filter(
            job => job.status === "closed"
        ).length;


    const expired =
        publishedJobs.filter(
            job => job.status === "expired"
        ).length;


    const totalPublished =
        document.getElementById(
            "totalPublished"
        );

    const activeJobs =
        document.getElementById(
            "activeJobs"
        );

    const closedJobs =
        document.getElementById(
            "closedJobs"
        );

    const expiringJobs =
        document.getElementById(
            "expiringJobs"
        );


    if (totalPublished) {
        totalPublished.textContent = total;
    }


    if (activeJobs) {
        activeJobs.textContent = active;
    }


    if (closedJobs) {
        closedJobs.textContent = closed;
    }


    if (expiringJobs) {

        const today =
            new Date();

        today.setHours(0, 0, 0, 0);


        const sevenDays =
            new Date(today);

        sevenDays.setDate(
            today.getDate() + 7
        );


        const expiring =
            publishedJobs.filter(job => {

                if (job.status !== "published") {
                    return false;
                }


                const expiry =
                    new Date(
                        job.expiresAt +
                        "T00:00:00"
                    );


                return (
                    expiry >= today &&
                    expiry <= sevenDays
                );

            }).length;


        expiringJobs.textContent =
            expiring;

    }

}



/* ==================================================
   RESULTS
================================================== */

function updateResults() {

    const total =
        filteredJobs.length;


    if (resultsCount) {

        resultsCount.textContent =
            `${total} ${total === 1 ? "job" : "jobs"}`;

    }


    const totalPages =
        Math.max(
            1,
            Math.ceil(
                total / jobsPerPage
            )
        );


    if (currentPageNumber > totalPages) {

        currentPageNumber =
            totalPages;

    }


    const start =
        total === 0
            ? 0
            : (currentPageNumber - 1) *
              jobsPerPage + 1;


    const end =
        Math.min(
            currentPageNumber * jobsPerPage,
            total
        );


    if (paginationInfo) {

        paginationInfo.textContent =
            total === 0
                ? "No jobs found"
                : `Showing ${start}–${end} of ${total} jobs`;

    }


    if (currentPage) {

        currentPage.textContent =
            total === 0
                ? "0"
                : currentPageNumber;

    }


    if (previousPage) {

        previousPage.disabled =
            currentPageNumber <= 1;

    }


    if (nextPage) {

        nextPage.disabled =
            currentPageNumber >= totalPages;

    }

}



/* ==================================================
   EMPTY STATE
================================================== */

function updateEmptyState() {

    const hasResults =
        filteredJobs.length > 0;


    if (publishedEmpty) {

        publishedEmpty.classList.toggle(
            "hidden",
            hasResults
        );

    }


    if (tableBody) {

        tableBody.parentElement
            .classList.toggle(
                "hidden",
                !hasResults
            );

    }


    if (mobileList) {

        mobileList.classList.toggle(
            "hidden",
            !hasResults
        );

    }

}



