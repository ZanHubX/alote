/* ==================================================
   CLOSE JOB
================================================== */

if (closeJobButton) {

    closeJobButton.addEventListener(
        "click",
        () => {

            const title =
                document.getElementById(
                    "modalJobTitle"
                ).textContent;


            const job =
                publishedJobs.find(
                    item =>
                        item.title === title
                );


            if (!job) {
                return;
            }


            const confirmed =
                window.confirm(
                    `Close "${job.title}"?\n\nThis job will no longer accept new applications.`
                );


            if (!confirmed) {
                return;
            }


            job.status =
                "closed";


            closeJobDetails();

            applyFilters();

            updateStatistics();

        }
    );

}



