/* ==================================================
   DATE VALIDATION
================================================== */

function validateDeadline() {

    const deadline =
        document.getElementById(
            "deadline"
        );


    if (!deadline) {

        return true;

    }


    if (!deadline.value) {

        return false;

    }


    const selectedDate =
        new Date(
            `${deadline.value}T23:59:59`
        );


    const today =
        new Date();


    today.setHours(
        0,
        0,
        0,
        0
    );


    return selectedDate > today;

}



/* ==================================================
   TEXT → ARRAY
================================================== */

function textToArray(text) {

    return text

        .split("\n")

        .map(item =>
            item.trim()
        )

        .filter(item =>
            item.length > 0
        );

}



